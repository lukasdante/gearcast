#!/usr/bin/env python3
"""Collect models-src/meta/*.json (written by each headless build) into src/models/kinds/meta.ts."""
import json, os, glob
HERE = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(HERE, '..', 'src', 'models', 'kinds', 'meta.ts')
metas = {}
for p in sorted(glob.glob(os.path.join(HERE, 'meta', '*.json'))):
    m = json.load(open(p))
    metas[m['kind']] = {k: m[k] for k in ('footprint', 'height', 'ports', 'tris', 'water') if k in m}
src = ['/** GENERATED by models-src/gen_meta.py from the Blender builds. Do not edit by hand. */',
       "import type { Port } from '../types';", '',
       'export interface KindMeta {', '  footprint: [number, number];', '  height: number;', '  ports: Port[];',
       '  tris: number;', '  /** WATER* surface height range (local metres) for level 0..1 */',
       '  water?: { min: number; max: number };', '}', '',
       'export const META: Record<string, KindMeta> = ' + json.dumps(metas, indent=2) + ';', '']
open(out, 'w').write('\n'.join(src))
print('wrote', out, list(metas))
