"""Incident report PDFs (pure Python, no LibreOffice).

PDFs are produced once — when a report is submitted (and for the historical reports at startup) —
and saved under var/rendered/, so downloads just serve the stored file.
"""
from __future__ import annotations

import io
from collections import OrderedDict
from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .config import RENDER_DIR

TEAL = colors.HexColor("#0f5f58")
TINT = colors.HexColor("#e8f1f0")
GRID = colors.HexColor("#9aaaa8")
PLANT = "Franklin Baker – Darong WWTP"

_ss = getSampleStyleSheet()
S = {
    "brand": ParagraphStyle("brand", parent=_ss["Normal"], fontName="Helvetica-Bold", fontSize=15, leading=19, textColor=TEAL),
    "sub": ParagraphStyle("sub", parent=_ss["Normal"], fontSize=8.5, textColor=colors.HexColor("#555555")),
    "title": ParagraphStyle("title", parent=_ss["Normal"], fontName="Helvetica-Bold", fontSize=14, alignment=1),
    "h": ParagraphStyle("h", parent=_ss["Normal"], fontName="Helvetica-Bold", fontSize=10, textColor=colors.HexColor("#0f3f3a")),
    "k": ParagraphStyle("k", parent=_ss["Normal"], fontName="Helvetica-Bold", fontSize=8.5, leading=10.5),
    "v": ParagraphStyle("v", parent=_ss["Normal"], fontSize=8.5, leading=10.5),
    "body": ParagraphStyle("body", parent=_ss["Normal"], fontSize=9, leading=12.5),
    "foot": ParagraphStyle("foot", parent=_ss["Normal"], fontSize=7, textColor=colors.HexColor("#777777")),
}


def _p(text, style="v"):
    return Paragraph(escape("" if text is None else str(text)).replace("\n", "<br/>"), S[style])


def _section(title: str, rows: list[tuple[str, object]]) -> list:
    data = [[_p(k, "k"), _p(v if v not in (None, "") else "—")] for k, v in rows]
    t = Table(data, colWidths=[52 * mm, None])
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, GRID), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f3f5f5")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    head = Table([[_p(title, "h")]], colWidths=["100%"])
    head.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), TINT), ("LINEBEFORE", (0, 0), (0, -1), 3, TEAL),
                              ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    return [Spacer(1, 7), KeepTogether([head, Spacer(1, 3), t])]


def _header(report_id: str, asset: str, date: str) -> list:
    meta = Table([[_p("Report no.", "k"), _p(report_id)], [_p("Asset", "k"), _p(asset)], [_p("Incident date", "k"), _p(date)]],
                 colWidths=[24 * mm, 36 * mm])
    meta.setStyle(TableStyle([("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]))
    top = Table([[[_p("GearCast", "brand"), _p(f"{PLANT} · Maintenance", "sub")], _p("INCIDENT REPORT", "title"), meta]],
                colWidths=[60 * mm, None, 62 * mm])
    top.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("LINEBELOW", (0, 0), (-1, -1), 2, TEAL),
                             ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    return [top]


def _signoff() -> list:
    t = Table([[_p("Reported by", "sub"), _p("Reviewed by (Head of Operations)", "sub"), _p("Date", "sub")]],
              colWidths=[None, None, 40 * mm], rowHeights=[16 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, GRID), ("VALIGN", (0, 0), (-1, -1), "BOTTOM")]))
    return [Spacer(1, 10), KeepTogether([t])]


def _build(story: list) -> bytes:
    buf = io.BytesIO()
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#777777"))
        canvas.drawString(14 * mm, 9 * mm, f"Generated by GearCast · {stamp}")
        canvas.drawRightString(A4[0] - 14 * mm, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()

    SimpleDocTemplate(buf, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm, topMargin=12 * mm, bottomMargin=15 * mm,
                      title="Incident report").build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


def draft_pdf(draft: dict) -> bytes:
    """The client's Equipment Incident Report form (Incident_Report_Form_v1.2.docx), filled and rendered to PDF."""
    from .docx_pdf import docx_bytes_to_pdf
    from .render import render_docx
    return docx_bytes_to_pdf(render_docx(draft), f"GearCast · {draft.get('report_id', '')} · generated {datetime.now():%Y-%m-%d %H:%M}")


def _legacy_draft_pdf(draft: dict) -> bytes:
    fields = sorted(draft.get("fields", []), key=lambda f: f["field_no"])
    by_no = {f["field_no"]: f.get("value") for f in fields}
    story = _header(draft.get("report_id") or by_no.get(1, ""), by_no.get(5) or draft.get("asset_id", ""), by_no.get(7, ""))
    if draft.get("summary"):
        story += _section("Summary", [("Narrative", draft["summary"])])
    groups: "OrderedDict[str, list]" = OrderedDict()
    for f in fields:
        groups.setdefault(f.get("section") or "Details", []).append((f.get("field") or f"Field {f['field_no']}", f.get("value")))
    for sec, rows in groups.items():
        story += _section(sec, rows)
    return _build(story + _signoff())


def history_draft(h: dict) -> dict:
    """Map a historical incident record onto the 37 template fields so it prints on the same form."""
    from .data import DATA
    a = DATA.asset.get(h.get("asset_id"), {}) if isinstance(DATA.asset, dict) else {}
    sev = str(h.get("severity") or "")
    vals = {
        1: h.get("report_id"), 2: str(h.get("incident_date") or ""), 3: sev,
        5: f"{h.get('asset_id')} – {a.get('description', '')}".strip(" –"), 6: a.get("location_node") or "",
        7: str(h.get("incident_date") or ""), 11: h.get("technician_inputs") or "Not recorded", 13: "Not recorded",
        15: h.get("procedure_used") or "", 16: "Not recorded", 17: "Not recorded",
        18: "None" if not h.get("production_loss_php") else "Curtail", 19: f"{float(h.get('production_loss_php') or 0):,.0f}",
        20: "Not recorded", 21: "None", 22: h.get("failure_mode") or ("Not applicable – near miss" if sev == "Near miss" else ""),
        23: "Not recorded", 24: h.get("root_cause") or "", 26: "", 27: h.get("corrective_action") or "",
        30: h.get("repair_or_replace") or "", 32: h.get("expected_report_text") or "", 36: "No change",
    }
    fields = [{"field_no": t["field_no"], "section": t["section"], "field": t["field"], "value": vals.get(t["field_no"], "Not recorded")}
              for t in DATA.ir_template]
    return {"report_id": h.get("report_id"), "asset_id": h.get("asset_id"), "fields": fields, "inputs": {},
            "linked": {}, "tables": {"repair_php": float(h.get("repair_cost_php") or 0)}, "summary": h.get("expected_report_text")}


def history_pdf(h: dict) -> bytes:
    return draft_pdf(history_draft(h))


def _legacy_history_pdf(h: dict) -> bytes:
    story = _header(h.get("report_id", ""), h.get("asset_id", ""), h.get("incident_date", ""))
    story += _section("Incident", [("Severity", h.get("severity")), ("Failure mode", h.get("failure_mode")),
                                   ("Root cause", h.get("root_cause")), ("Procedure used", h.get("procedure_used")),
                                   ("Technician inputs", h.get("technician_inputs"))])
    story += _section("Cost and decision", [("Repair cost (PHP)", h.get("repair_cost_php")),
                                            ("Production loss (PHP)", h.get("production_loss_php")),
                                            ("Repair or replace", h.get("repair_or_replace")),
                                            ("Corrective action", h.get("corrective_action")), ("Status", h.get("status"))])
    story += [Spacer(1, 7), _p("Report", "h"), Spacer(1, 3), _p(h.get("expected_report_text") or "No narrative recorded.", "body")]
    return _build(story + _signoff())


def pdf_path(report_id: str) -> Path:
    return RENDER_DIR / f"{report_id}.pdf"


def store(report_id: str, data: bytes) -> Path:
    p = pdf_path(report_id)
    p.write_bytes(data)
    return p
